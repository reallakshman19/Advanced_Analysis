import {
  ENGINEERING_PROPERTY_SPECS,
} from '../core/shared-piping-model/property-specs.js';
import { withConfiguredSourceAttributeAliases } from '../core/shared-piping-model/source-attribute-aliases.js';

/**
 * Run-scoped attributes for the synthetic pipes that fill the gaps between
 * fittings.
 *
 * SJSON does not model the straight pipe between two fittings as a source
 * object; the converter synthesises one, marks it AUTO_GENERATED_PIPE, and
 * gives it only what it can derive from the gap itself - the two end points,
 * the length, and the bore it already inherits from the adjacent fitting
 * (BORE_SOURCE records that). Everything the run carries and the gap geometry
 * cannot show is simply absent on those pipes.
 *
 * Insulation thickness is one of them. On the 1885S model every real fitting
 * states INSU 80mm and every synthetic pipe states nothing, so the mass
 * resolver refused to project pipe mass at all: it could not compute an
 * insulation mass from a thickness the component did not have, and absence is
 * not evidence that the run is bare.
 *
 * A synthetic pipe is the piece of run between the two fittings that bound it,
 * so when those fittings agree on a run-scoped value the gap between them
 * carries it. That is the only case treated as inheritance here:
 *
 *   - the entity must be marked AUTO_GENERATED_PIPE by the converter;
 *   - the value must be absent on the pipe itself, so a stated value always
 *     wins over an inherited one;
 *   - the nearest real neighbour on each side within the same branch must
 *     state the attribute, and they must agree. One neighbour stating it and
 *     the other silent, or the two disagreeing, is not resolved by picking
 *     one - the pipe keeps its absence and the disagreement is reported.
 *
 * Inherited values land in enrichedAttributes, never in the source
 * attributes, and each carries a <NAME>_SOURCE naming the neighbours it came
 * from. Evidence collection reads sourceAttributes and attributes first, so
 * this can only fill a gap and never overwrite what the source states.
 */

const AUTO_GENERATED_PIPE = 'AUTO_GENERATED_PIPE';

/**
 * Properties whose value belongs to the run rather than to the component.
 *
 * Deliberately short. A property qualifies only when a straight length of pipe
 * between two fittings necessarily shares it with them; anything a component
 * carries for itself (a weight, a rating, a catalogue reference) must not be
 * copied onto a neighbour.
 */
export const INHERITABLE_RUN_PROPERTIES = Object.freeze(['insulationThicknessMm']);

export const AUTO_PIPE_RUN_ATTRIBUTE_INHERITED = 'AUTO_PIPE_RUN_ATTRIBUTE_INHERITED';
export const AUTO_PIPE_RUN_ATTRIBUTE_UNRESOLVED = 'AUTO_PIPE_RUN_ATTRIBUTE_UNRESOLVED';

/**
 * @param {Array<object>} entities Normalized workspace entities, in source order.
 * @param {object} [options]
 * @param {object} [options.sourceAttributeAliases] Project-configured extra
 *   source attribute names, so a project that teaches the importer a new word
 *   for an inheritable property gets the inheritance too.
 * @returns {Array<object>} The same entities, with synthetic pipes carrying the
 *   run attributes their bounding fittings agree on.
 */
export function withAdjacentRunAttributes(entities, options = {}) {
  if (!Array.isArray(entities) || !entities.some(isAutoGeneratedPipe)) return entities;
  const names = inheritableAttributeNames(options.sourceAttributeAliases);
  if (!names.length) return entities;
  const byBranch = groupByParent(entities);
  return entities.map((entity) => {
    if (!isAutoGeneratedPipe(entity)) return entity;
    const siblings = byBranch.get(parentKey(entity)) || [];
    const index = siblings.indexOf(entity);
    const inherited = {};
    const diagnostics = [];
    for (const name of names) {
      if (statedValue(entity, name) !== null) continue;
      const resolution = resolveFromNeighbours(siblings, index, name);
      if (resolution.value === null) {
        if (resolution.diagnostic) diagnostics.push(resolution.diagnostic);
        continue;
      }
      inherited[name] = resolution.value;
      inherited[`${name}_SOURCE`] = `inherited from ${name} of adjacent ${resolution.from.join(' and ')}`;
      diagnostics.push({
        code: AUTO_PIPE_RUN_ATTRIBUTE_INHERITED,
        severity: 'INFO',
        message: `${name} ${resolution.value} inherited by the synthetic pipe from ${resolution.from.join(' and ')}, which agree.`,
        scope: entity.entityId,
        attribute: name,
      });
    }
    if (!Object.keys(inherited).length && !diagnostics.length) return entity;
    return withEnrichedAttributes(entity, inherited, diagnostics);
  });
}

function resolveFromNeighbours(siblings, index, name) {
  const before = sideEvidence(siblings, index, -1, name);
  const after = sideEvidence(siblings, index, 1, name);
  // A silent neighbour is not the same as no neighbour. The synthetic head and
  // tail pipes run from the branch boundary to the first (or last) fitting, so
  // there is nothing on the outboard side to agree with and the one fitting
  // that bounds them governs. A neighbour that exists and says nothing is the
  // ambiguous case: the run may start, end, or change at exactly that fitting,
  // so the pipe keeps its absence.
  const stated = [before, after].filter((side) => side.stating);
  if (!stated.length) return { value: null, diagnostic: null };
  if (stated.length === 1) {
    const only = [before, after].find((side) => !side.stating);
    if (only.present) return { value: null, diagnostic: null };
    return { value: stated[0].stating.value, from: [stated[0].stating.entity.entityId], diagnostic: null };
  }
  const before_ = stated[0].stating;
  const after_ = stated[1].stating;
  return agreement(before_, after_, siblings, index, name);
}

function agreement(before, after, siblings, index, name) {
  if (before.value !== after.value) {
    return {
      value: null,
      diagnostic: {
        code: AUTO_PIPE_RUN_ATTRIBUTE_UNRESOLVED,
        severity: 'WARNING',
        message: `${name} is ${before.value} on ${before.entity.entityId} and ${after.value} on ${after.entity.entityId}; the synthetic pipe between them keeps no value rather than picking one.`,
        scope: siblings[index].entityId,
        attribute: name,
      },
    };
  }
  return { value: before.value, from: [before.entity.entityId, after.entity.entityId], diagnostic: null };
}

/**
 * What one side of the synthetic pipe offers: whether any real component lies
 * that way at all, and the nearest one that states the attribute.
 */
function sideEvidence(siblings, index, step, name) {
  let present = false;
  for (let at = index + step; at >= 0 && at < siblings.length; at += step) {
    const entity = siblings[at];
    if (isAutoGeneratedPipe(entity)) continue;
    present = true;
    const value = statedValue(entity, name);
    if (value !== null) return { present: true, stating: { entity, value } };
  }
  return { present, stating: null };
}

function inheritableAttributeNames(configuredAliases) {
  const specs = withConfiguredSourceAttributeAliases(ENGINEERING_PROPERTY_SPECS, configuredAliases);
  const names = [];
  for (const property of INHERITABLE_RUN_PROPERTIES) {
    for (const alias of specs[property]?.aliases || []) {
      if (!names.includes(alias)) names.push(alias);
    }
  }
  return names;
}

function statedValue(entity, name) {
  const properties = entity?.properties || {};
  for (const root of [properties.sourceAttributes, properties.attributes, properties.enrichedAttributes]) {
    if (!root || typeof root !== 'object') continue;
    const value = root[name];
    if (value === undefined || value === null || value === '') continue;
    return typeof value === 'string' ? value.trim() : value;
  }
  return null;
}

function withEnrichedAttributes(entity, inherited, diagnostics) {
  const properties = entity.properties || {};
  return Object.freeze({
    ...entity,
    properties: Object.freeze({
      ...properties,
      enrichedAttributes: Object.freeze({ ...(properties.enrichedAttributes || {}), ...inherited }),
      diagnostics: Object.freeze([...(properties.diagnostics || []), ...diagnostics]),
    }),
  });
}

function groupByParent(entities) {
  const groups = new Map();
  for (const entity of entities) {
    const key = parentKey(entity);
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(entity);
  }
  return groups;
}

function parentKey(entity) {
  return String(entity?.parentSourceNodeKey || entity?.branchId || '');
}

function isAutoGeneratedPipe(entity) {
  return String(entity?.properties?.attributes?.[AUTO_GENERATED_PIPE] || '').toLowerCase() === 'true';
}
